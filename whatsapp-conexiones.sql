
CREATE TABLE IF NOT EXISTS whatsapp_conexiones_meta (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL
    REFERENCES empresas(id) ON DELETE RESTRICT,
  waba_id TEXT NOT NULL,
  phone_number_id TEXT NOT NULL UNIQUE,
  token_cifrado TEXT NOT NULL,
  estado TEXT NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'activo', 'error', 'desconectado')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_whatsapp_meta_empresa
ON whatsapp_conexiones_meta (empresa_id);
